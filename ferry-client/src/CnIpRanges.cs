        /// <summary>这个 IP 属于国内分配的地址段吗？</summary>
        public static bool Contains(IPAddress ip)
        {
            if (ip == null || ip.AddressFamily != AddressFamily.InterNetwork) return false;
            var b = ip.GetAddressBytes();

            // 私网 / 回环 / 链路本地 / CGNAT：都按「不该走境外」处理
            if (b[0] == 10 || b[0] == 127) return true;
            if (b[0] == 172 && b[1] >= 16 && b[1] <= 31) return true;
            if (b[0] == 192 && b[1] == 168) return true;
            if (b[0] == 169 && b[1] == 254) return true;
            if (b[0] == 100 && b[1] >= 64 && b[1] <= 127) return true;

            // 已知的「/16 里混了境外地址」的例外。
            // 位图是 /16 粒度，而 APNIC 是 /24 级分配：1.1.0.0/24 是中国的、
            // 1.1.1.0/24 是 Cloudflare 的 —— 同一个 /16。只列会造成实际影响的几个。
            if (IsKnownForeign(b)) return false;

            // 位图按「小端」打包：bitmap 的第 i 个字节 = word[i/4] 的第 (i%4) 个字节，
            // 字节内的第 j 位就是 /16 段 sequence 里的第 j 个。这样查表只要
            // word = _bits[s16 / 32]、bit = s16 % 32，不用做任何反转。
            int s16 = (b[0] << 8) | b[1];
            uint word = _bits[s16 >> 5];
            return (word & (1u << (s16 & 31))) != 0;
        }

        /// <summary>已知的境外关键地址（位图精度损失的例外）。</summary>
        static bool IsKnownForeign(byte[] b)
        {
            if (b[0] == 1 && b[1] == 1 && b[2] == 1) return true;        // Cloudflare DNS
            if (b[0] == 1 && b[1] == 0 && b[2] == 0 && b[3] == 1) return true;
            if (b[0] == 8 && b[1] == 8 && b[2] == 8 && b[3] == 8) return true;    // Google DNS
            if (b[0] == 8 && b[1] == 8 && b[2] == 4 && b[3] == 4) return true;
            if (b[0] == 9 && b[1] == 9 && b[2] == 9 && b[3] == 9) return true;    // Quad9
            if (b[0] == 208 && b[1] == 67 && b[2] == 222 && b[3] == 222) return true;
            if (b[0] == 104 && b[1] >= 16 && b[1] <= 31) return true;    // Cloudflare
            if (b[0] == 172 && b[1] == 67) return true;
            if (b[0] == 162 && b[1] == 159) return true;
            if (b[0] == 142 && b[1] == 250) return true;
            if (b[0] == 188 && b[1] == 114) return true;
            return false;
        }

        /// <summary>覆盖的 /16 段数（诊断用）。</summary>
        public static int Count
        {
            get
            {
                int n = 0;
                foreach (var w in _bits) n += PopCount(w);
                return n;
            }
        }

        static int PopCount(uint x)
        {
            int n = 0;
            while (x != 0) { n += (int)(x & 1); x >>= 1; }
            return n;
        }
