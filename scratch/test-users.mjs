import { UserStore, Authenticator, parseBasicAuth, parseSocks5Auth } from '../tools/proxy-users.mjs';
import fs from 'node:fs';
const f = './scratch/test-users.json';
try { fs.unlinkSync(f); } catch {}
const store = new UserStore(f);
const u = store.add('张三');
console.log('新增:', u.name, '令牌:', u.token);
const auth = new Authenticator(store, { logger: { warn() {} } });
console.log('正确凭据:', auth.verify('张三', u.token).ok);
console.log('错误令牌:', auth.verify('张三', 'wrong').reason);
console.log('未知用户:', auth.verify('李四', 'x').reason);
store.update('张三', { enabled: false });
console.log('禁用后:', auth.verify('张三', u.token).reason);
store.update('张三', { enabled: true });
const s = auth.open('张三');
s.addIn(100); s.addOut(200);
const snap = auth.snapshot();
console.log('summary:', JSON.stringify(snap.summary));
console.log('live:', JSON.stringify(snap.users[0].live));
s.close();
const b = 'Basic ' + Buffer.from('张三:abc-def').toString('base64');
console.log('Basic:', JSON.stringify(parseBasicAuth(b)));
const nm = Buffer.from('张三','utf8'), tk = Buffer.from('abc','utf8');
const pkt = Buffer.concat([Buffer.from([1, nm.length]), nm, Buffer.from([tk.length]), tk]);
console.log('SOCKS5:', JSON.stringify(parseSocks5Auth(pkt)));
fs.unlinkSync(f);
console.log('ALL OK');
